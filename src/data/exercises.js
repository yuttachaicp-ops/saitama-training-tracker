export function getExercise(id) {
  return EXERCISES[id] || null;
}

/** แสดงเป้าหมายเป็นข้อความ เช่น "12 ครั้ง × 3 เซต" */
export function formatTarget(ex, reps, sets) {
  const u = ex?.unit || UNIT.REPS;
  let r;
  if (u === UNIT.SECONDS) r = `${reps} วินาที`;
  else if (u === UNIT.REPS_SIDE) r = `${reps} ครั้ง/ข้าง`;
  else r = `${reps} ครั้ง`;
  return `${r} × ${sets} เซต`;
}

export function unitLabel(ex) {
  const u = ex?.unit || UNIT.REPS;
  if (u === UNIT.SECONDS) return 'วินาที';
  if (u === UNIT.REPS_SIDE) return 'ครั้ง/ข้าง';
  return 'ครั้ง';
}
